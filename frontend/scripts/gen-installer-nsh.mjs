// Generates build/installer.nsh (included by electron-builder's NSIS installer) from shell-menus.json.
// Install: registers Explorer context menus + "Open with" for all users (SHCTX = HKLM for per-machine installs).
// Uninstall: removes only application-owned keys. User documents, templates and exports are never touched.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { buildEntries, ownedKeys, menus } = require("../electron/shell-entries.cjs");
const here = path.dirname(fileURLToPath(import.meta.url));

const exe = "$INSTDIR\\${APP_EXECUTABLE_FILENAME}";
const q = (s) => s.replace(/\$(?!INSTDIR|\{APP_EXECUTABLE_FILENAME\})/g, "$$$$").replace(/'/g, "$\\'");
const lines = [
  "; Generated by scripts/gen-installer-nsh.mjs from electron/shell-menus.json - do not edit by hand.",
  "!macro customInstall",
  "  !ifdef APP_64",
  "    SetRegView 64",
  "  !endif",
  '  DetailPrint "Registering PDF Test Designer in the Windows Explorer context menu..."',
];
for (const e of buildEntries(exe)) {
  const key = `Software\\Classes\\${e.path}`;
  for (const [name, value] of Object.entries(e.values)) {
    if (value.startsWith("dword:")) lines.push(`  WriteRegDWORD SHCTX '${q(key)}' '${q(name)}' ${parseInt(value.slice(6), 16)}`);
    else lines.push(`  WriteRegStr SHCTX '${q(key)}' '${q(name)}' '${q(value)}'`);
  }
}
lines.push(`  WriteRegStr SHCTX 'Software\\Classes\\Applications\\\${APP_EXECUTABLE_FILENAME}' 'FriendlyAppName' '${menus.title}'`);
for (const ext of menus.openWithExtensions) lines.push(`  WriteRegStr SHCTX 'Software\\Classes\\Applications\\\${APP_EXECUTABLE_FILENAME}\\SupportedTypes' '${ext}' ''`);
lines.push("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'", "!macroend", "");
lines.push("!macro customUnInstall", "  !ifdef APP_64", "    SetRegView 64", "  !endif", '  DetailPrint "Removing PDF Test Designer context menu entries..."');
for (const k of ownedKeys()) lines.push(`  DeleteRegKey SHCTX 'Software\\Classes\\${q(k)}'`);
for (const k of ownedKeys()) lines.push(`  DeleteRegKey HKCU 'Software\\Classes\\${q(k)}'`);
lines.push(`  DeleteRegKey SHCTX 'Software\\Classes\\Applications\\\${APP_EXECUTABLE_FILENAME}'`);
for (const ext of menus.openWithExtensions) {
  lines.push(`  DeleteRegValue SHCTX 'Software\\Classes\\${ext}\\OpenWithProgids' '${menus.progId}'`);
  lines.push(`  DeleteRegValue HKCU 'Software\\Classes\\${ext}\\OpenWithProgids' '${menus.progId}'`);
}
lines.push("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'", "!macroend", "");
fs.mkdirSync(path.join(here, "..", "build"), { recursive: true });
fs.writeFileSync(path.join(here, "..", "build", "installer.nsh"), lines.join("\r\n"), "utf8");
console.log(`build/installer.nsh written (${lines.length} lines)`);
